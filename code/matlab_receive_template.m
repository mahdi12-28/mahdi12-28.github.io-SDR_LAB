% Requires the Pluto support package and the course MATLAB toolboxes.
rx = sdrrx('Pluto', ...
    'RadioID', 'ip:192.168.1.10', ...
    'CenterFrequency', 945e6, ...
    'BasebandSampleRate', 2.6e6, ...
    'GainSource', 'Manual', ...
    'Gain', 20, ...
    'SamplesPerFrame', 4096, ...
    'OutputDataType', 'double');
cleanupRadio = onCleanup(@() release(rx));
disp(info(rx));
sa = spectrumAnalyzer('SampleRate', 2.6e6);
cleanupAnalyzer = onCleanup(@() release(sa));
for k = 1:200
    samples = rx();
    sa(samples);
end
